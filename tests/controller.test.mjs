import test from 'node:test';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
import {Vault} from '../extension/lib/vault.mjs';
if (!globalThis.crypto) globalThis.crypto=webcrypto;
function event(){let listener;return {addListener:f=>{listener=f;},emit:(...args)=>listener?.(...args)};}
async function harness({multi=false,failInsert=false,failCreate=false,failLogout=false,policy=null}={}) {
 const data={},calls=[],drafts=new Map();let draftCount=0;
 const b={storage:{managed:{get:async()=>policy || {}},local:{get:async key=>({[key]:data[key]}),set:async o=>Object.assign(data,o),remove:async key=>{delete data[key];}}},
 runtime:{id:'test',getURL:p=>'moz-extension://test/'+p,onMessage:event(),openOptionsPage:async()=>{}},
 browserAction:{onClicked:event()},composeAction:{onClicked:event()},windows:{onRemoved:event(),getLastFocused:async()=>({id:1}),create:async()=>({id:2})},
 meetlingNative:{encrypt:async v=>v,decrypt:async v=>v,onInvoke:event(),capture:async()=>{const key=String(++draftCount);drafts.set(key,{});return key;},release:async()=>{},
 markPending:async key=>{const d=drafts.get(key);if(d.pending)throw new Error('Already pending');d.pending=true;},
 apply:async(key,c)=>{if(failInsert)throw new Error('Editor closed');drafts.get(key).conference=c;}}};
 data.configuration={baseUrl:'https://example.org/sub/'};await new Vault(b).save('https://example.org/sub/',{token:'opaque',name:'Test'});
 globalThis.browser=b;globalThis.fetch=async(url,options)=>{
  calls.push({url,options});
  if(url.endsWith('server')) return {ok:true,status:200,text:async()=>multi?'[{"id":1,"name":"One"},{"id":2,"name":"Two"}]':'[{"id":1,"name":"One"}]'};
  if(url.endsWith('logout')) {if(failLogout)throw new TypeError('network');return {ok:true,status:200,text:async()=>'{"token":null}'};}
  if(failCreate)throw new TypeError('network');
  return {ok:true,status:200,text:async()=>'{"id":3,"title":"T","url":"https://room.example/3"}'};
 };
 await import('../extension/background.mjs?run='+crypto.randomUUID());
 const send=(action,extra={})=>b.runtime.onMessage.emit({action,...extra},{id:'test',url:'moz-extension://test/ui/panel.html'});
 // Capture the panel identifier generated by toolbar activation via its URL.
 let panel;
 b.windows.create=async data=>{panel=new URL(data.url).searchParams.get('panel');return {id:2};};
 await b.browserAction.onClicked.emit({windowId:1});await new Promise(r=>setImmediate(r));
 return {b,data,calls,drafts,send:(action,extra={})=>send(action,{panel,...extra})};
}
test('multiple servers require confirmed selection; cancelling sends no create',async()=>{
 const h=await harness({multi:true});const state=await h.send('prepare');assert.equal(state.selection.length,2);
 assert.equal(h.calls.filter(c=>c.options.method==='POST').length,0);
 await h.send('create',{serverId:'2'});assert.equal(h.calls.filter(c=>c.options.method==='POST').length,1);
 assert.equal(h.calls.at(-1).options.body.toString(),'server_id=2');assert(h.drafts.get('1').conference);
 await h.send('create',{serverId:'2'});assert.equal(h.calls.filter(c=>c.options.method==='POST').length,1);
});
test('uncertain create outcome keeps pending marker and does not retry',async()=>{
 const h=await harness({failCreate:true});const state=await h.send('prepare');assert(state.status.includes('Ausgang unklar'));assert(h.drafts.get('1').pending);
 await h.send('prepare');assert.equal(h.calls.filter(c=>c.options.method==='POST').length,1);
});
test('insertion failure exposes returned conference for manual recovery',async()=>{
 const h=await harness({failInsert:true});const state=await h.send('prepare');assert.equal(state.recovery.url,'https://room.example/3');assert(state.recovery.bodyText.includes('editConference_id=3'));
 assert(!JSON.stringify(state).includes('opaque'));const again=await h.send('prepare');assert.equal(again.recovery.url,'https://room.example/3');assert.equal(h.calls.filter(c=>c.options.method==='POST').length,1);
});
test('failed revocation retains token until explicit local logout',async()=>{
 const h=await harness({failLogout:true});const state=await h.send('logout');assert(state.status.includes('nicht bestätigt'));assert.equal(state.name,'Test');
 assert(Object.keys(h.data).some(k=>k.startsWith('token-')));
 const local=await h.send('localLogout');assert.equal(local.name,null);assert(!Object.keys(h.data).some(k=>k.startsWith('token-')));
});
test('invalid managed config fails closed and blocks user edits',async()=>{
 const h=await harness({policy:{configuration:{baseUrl:'http://invalid'}}});const state=await h.send('state');assert.equal(state.managed,true);assert.equal(state.configured,false);
 await h.send('saveConfig',{configuration:{baseUrl:'https://other.example/'}});assert.equal(h.data.configuration.baseUrl,'https://example.org/sub/');
});
